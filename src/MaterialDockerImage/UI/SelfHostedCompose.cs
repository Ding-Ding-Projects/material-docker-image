using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace MaterialDockerImage.UI;

/// <summary>The files written for one deployment.</summary>
public sealed record SelfHostedFiles(string Compose, string Env, string Settings);

/// <summary>Settings of a deployed project that are not secret, saved beside the Compose file so Update can re-render it.</summary>
public sealed record SelfHostedSaved(string App, string Project, SelfHostedDatabase Database, SelfHostedStorage Storage, string Folder, string TimeZone, string AdminUser,
    string PublicHost, List<string> TrustedHosts, Dictionary<string, int> HostPorts, DateTimeOffset Created, List<string> Images)
{
    public SelfHostedOptions ToOptions() => new()
    {
        Project = Project, Database = Database, Storage = Storage, Folder = Folder, TimeZone = TimeZone, AdminUser = AdminUser,
        PublicHost = PublicHost, TrustedHosts = TrustedHosts, HostPorts = new Dictionary<string, int>(HostPorts, StringComparer.Ordinal),
    };
}

/// <summary>
/// Renders a catalogue entry and its options into compose.yaml, .env and a settings file. compose.yaml contains no
/// secret: every password, key and site-specific value is a reference to a .env variable.
/// </summary>
public static class SelfHostedCompose
{
    private static readonly JsonSerializerOptions Json = new() { WriteIndented = true, Converters = { new System.Text.Json.Serialization.JsonStringEnumConverter() } };

    public static SelfHostedFiles Render(SelfHostedApp app, SelfHostedOptions options, DateTimeOffset? created = null) =>
        new(ComposeYaml(app, options), EnvFile(app, options), JsonSerializer.Serialize(Saved(app, options, created ?? DateTimeOffset.UtcNow), Json));

    public static SelfHostedSaved Saved(SelfHostedApp app, SelfHostedOptions o, DateTimeOffset created) =>
        new(app.Id, o.Project, o.Database, o.Storage, o.Folder, o.TimeZone, o.AdminUser, o.PublicHost, [.. o.TrustedHosts],
            app.Ports.ToDictionary(p => p.Key, p => o.Port(app, p.Key), StringComparer.Ordinal), created, [.. app.Services(o).Select(s => s.Image)]);

    public static SelfHostedSaved? ReadSaved(string json)
    {
        try { return JsonSerializer.Deserialize<SelfHostedSaved>(json, Json); }
        catch (JsonException) { return null; }
    }

    /// <summary>Double-quoted YAML scalar (JSON-compatible escapes).</summary>
    public static string Q(string value)
    {
        var sb = new StringBuilder("\"");
        foreach (var c in value)
        {
            switch (c)
            {
                case '"': sb.Append("\\\""); break;
                case '\\': sb.Append("\\\\"); break;
                case '\n': sb.Append("\\n"); break;
                case '\r': sb.Append("\\r"); break;
                case '\t': sb.Append("\\t"); break;
                default:
                    if (c < ' ') sb.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture)); else sb.Append(c);
                    break;
            }
        }
        return sb.Append('"').ToString();
    }

    private static string Flow(IEnumerable<string> items) => "[" + string.Join(", ", items.Select(Q)) + "]";

    /// <summary>Host folder for one volume in folder mode, with forward slashes so Compose reads it the same on every platform.</summary>
    public static string HostFolder(SelfHostedOptions o, SelfHostedVolume v) => Path.Combine(o.Folder, o.Project, v.Key).Replace('\\', '/');

    /// <summary>True when the volume is a Docker named volume for these options (always for databases, which are slow
    /// and can fail ownership checks on Windows folders).</summary>
    public static bool IsNamed(SelfHostedOptions o, SelfHostedVolume v) => o.Storage == SelfHostedStorage.NamedVolumes || v.Database;

    public static string ComposeYaml(SelfHostedApp app, SelfHostedOptions o)
    {
        var services = app.Services(o);
        var volumes = app.VolumesFor(o.Database).ToList();
        var sb = new StringBuilder();
        sb.Append("# ").Append(app.Name).Append(" · generated by Material Docker Image.\n");
        sb.Append("# Passwords, keys and site-specific values are in the .env file beside this one; this file holds none.\n");
        sb.Append("name: ").Append(Q(o.Project)).Append('\n');
        sb.Append("services:\n");
        foreach (var s in services)
        {
            sb.Append("  ").Append(s.Name).Append(":\n");
            sb.Append("    image: ").Append(Q(s.Image)).Append('\n');
            if (s.Build is { } build)
            {
                // Compose interpolates $ in the whole file, dockerfile_inline included, so the Dockerfile's own $ are doubled.
                sb.Append("    build:\n");
                sb.Append("      context: ").Append(Q(build.Context)).Append('\n');
                sb.Append("      dockerfile_inline: ").Append(Q(build.Dockerfile.Replace("$", "$$", StringComparison.Ordinal))).Append('\n');
            }
            sb.Append("    restart: unless-stopped\n");
            sb.Append("    labels:\n");
            sb.Append("      ").Append(SelfHostedRules.Label).Append(": ").Append(Q(app.Id)).Append('\n');
            if (s.Command.Count > 0) sb.Append("    command: ").Append(Flow(s.Command)).Append('\n');
            if (s.ShmSize != null) sb.Append("    shm_size: ").Append(Q(s.ShmSize)).Append('\n');
            if (s.Environment.Count > 0)
            {
                sb.Append("    environment:\n");
                foreach (var (key, value) in s.Environment) sb.Append("      ").Append(key).Append(": ").Append(Q(value)).Append('\n');
            }
            var ports = app.Ports.Where(p => p.Service == s.Name).ToList();
            if (ports.Count > 0)
            {
                sb.Append("    ports:\n");
                foreach (var p in ports)
                    foreach (var protocol in p.Protocol.Split('+'))
                        sb.Append("      - target: ").Append(p.ContainerPort.ToString(CultureInfo.InvariantCulture)).Append('\n')
                          .Append("        published: ").Append(Q(o.Port(app, p.Key).ToString(CultureInfo.InvariantCulture))).Append('\n')
                          .Append("        protocol: ").Append(protocol).Append('\n');
            }
            var mounts = volumes.Where(v => v.Service == s.Name).ToList();
            if (mounts.Count > 0)
            {
                sb.Append("    volumes:\n");
                foreach (var v in mounts)
                {
                    if (IsNamed(o, v))
                        sb.Append("      - type: volume\n        source: ").Append(v.Key).Append("\n        target: ").Append(Q(v.ContainerPath)).Append('\n');
                    else
                        sb.Append("      - type: bind\n        source: ").Append(Q(HostFolder(o, v))).Append("\n        target: ").Append(Q(v.ContainerPath))
                          .Append("\n        bind:\n          create_host_path: true\n");
                }
            }
            if (s.DependsOnHealthy.Count + s.DependsOnStarted.Count > 0)
            {
                sb.Append("    depends_on:\n");
                foreach (var d in s.DependsOnHealthy) sb.Append("      ").Append(d).Append(":\n        condition: service_healthy\n");
                foreach (var d in s.DependsOnStarted) sb.Append("      ").Append(d).Append(":\n        condition: service_started\n");
            }
            if (s.Healthcheck.Count > 0)
            {
                sb.Append("    healthcheck:\n");
                sb.Append("      test: ").Append(Flow(s.Healthcheck)).Append('\n');
                sb.Append("      interval: 15s\n      timeout: 10s\n      retries: 10\n");
                sb.Append("      start_period: ").Append(s.HealthStartPeriod).Append('\n');
            }
        }
        var named = volumes.Where(v => IsNamed(o, v)).ToList();
        if (named.Count > 0)
        {
            sb.Append("volumes:\n");
            foreach (var v in named)
                sb.Append("  ").Append(v.Key).Append(":\n    labels:\n      ").Append(SelfHostedRules.Label).Append(": ").Append(Q(app.Id)).Append('\n');
        }
        return sb.ToString();
    }

    /// <summary>A .env value: plain when it is a simple token, single-quoted (literal, no interpolation) otherwise.</summary>
    public static string EnvValue(string value)
    {
        if (value.IndexOfAny(['\'', '\n', '\r']) >= 0) throw new ArgumentException("A .env value cannot contain quotes or line breaks.");
        return Regex.IsMatch(value, "^[A-Za-z0-9_./:+=@,-]*$", RegexOptions.CultureInvariant, TimeSpan.FromMilliseconds(100)) ? value : "'" + value + "'";
    }

    /// <summary>Variables the Compose file references, with their values. Secrets come last so a quick look shows the settings first.</summary>
    public static List<KeyValuePair<string, string>> EnvVariables(SelfHostedApp app, SelfHostedOptions o)
    {
        var hosts = new List<string> { "localhost", "127.0.0.1" };
        hosts.AddRange(o.TrustedHosts.Where(h => SelfHostedRules.ValidateHost(h) == null));
        if (SelfHostedRules.ValidateHost(o.PublicHost) == null) hosts.Add(o.PublicHost);
        var list = new List<KeyValuePair<string, string>>
        {
            new("TZ", o.TimeZone),
            new("PUBLIC_HOST", o.PublicHost),
            new("TRUSTED_HOSTS", string.Join(' ', hosts.Distinct(StringComparer.OrdinalIgnoreCase))),
        };
        if (app.AdminUser != null) list.Add(new("ADMIN_USER", o.AdminUser));
        foreach (var p in app.Ports) list.Add(new(SelfHostedCatalogue.PortVariable(p.Key), o.Port(app, p.Key).ToString(CultureInfo.InvariantCulture)));
        foreach (var secret in app.SecretsFor(o.Database)) list.Add(new(secret.Key, o.Secrets.TryGetValue(secret.Key, out var v) ? v : ""));
        return list;
    }

    public static string EnvFile(SelfHostedApp app, SelfHostedOptions o)
    {
        var sb = new StringBuilder();
        sb.Append("# ").Append(app.Name).Append(" settings for the Compose project ").Append(o.Project).Append(".\n");
        sb.Append("# Generated by Material Docker Image. This file holds passwords and keys: keep it private.\n");
        foreach (var (key, value) in EnvVariables(app, o)) sb.Append(key).Append('=').Append(EnvValue(value)).Append('\n');
        return sb.ToString();
    }

    /// <summary>The .env text with every secret value replaced, for review screens.</summary>
    public static string MaskedEnv(SelfHostedApp app, SelfHostedOptions o)
    {
        var secretKeys = app.SecretsFor(o.Database).Select(s => s.Key).ToHashSet(StringComparer.Ordinal);
        var sb = new StringBuilder();
        foreach (var (key, value) in EnvVariables(app, o)) sb.Append(key).Append('=').Append(secretKeys.Contains(key) ? "•••••••• (generated, " + value.Length.ToString(CultureInfo.InvariantCulture) + " characters)" : EnvValue(value)).Append('\n');
        return sb.ToString();
    }

    /// <summary>docker compose arguments for one project, run with the files in <paramref name="folder"/>.</summary>
    public static List<string> ComposeArgs(string project, string folder, params string[] command)
    {
        var args = new List<string> { "compose", "-p", project, "-f", Path.Combine(folder, "compose.yaml"), "--env-file", Path.Combine(folder, ".env") };
        args.AddRange(command);
        return args;
    }

    /// <summary>Pairs of (current, new) image references that differ between a saved deployment and the catalogue now.</summary>
    public static List<(string Current, string Next)> ImageChanges(SelfHostedApp app, SelfHostedSaved saved)
    {
        var next = app.Services(saved.ToOptions()).Select(s => s.Image).ToList();
        var changes = new List<(string, string)>();
        foreach (var image in next)
        {
            var repo = Repository(image);
            var current = saved.Images.FirstOrDefault(i => Repository(i) == repo);
            if (current != null && current != image) changes.Add((current, image));
            if (current == null) changes.Add(("(new service)", image));
        }
        return changes;
    }

    /// <summary>Image reference without its tag.</summary>
    public static string Repository(string image)
    {
        var at = image.IndexOf('@');
        if (at > 0) image = image[..at];
        var slash = image.LastIndexOf('/');
        var colon = image.LastIndexOf(':');
        return colon > slash ? image[..colon] : image;
    }

    /// <summary>The tag of an image reference, or "" when it has none.</summary>
    public static string Tag(string image)
    {
        var at = image.IndexOf('@');
        if (at > 0) image = image[..at];
        var slash = image.LastIndexOf('/');
        var colon = image.LastIndexOf(':');
        return colon > slash ? image[(colon + 1)..] : "";
    }
}
